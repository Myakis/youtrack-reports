// Тексты запросов к модели: отчёт по задачам и обоснование повышения.
import { PROMPT } from './export';

export type Goal = 'report' | 'promo';

export interface PromoInfo {
  name: string;       // «Иван Петров (i.petrov)»
  period?: string;    // «01.01.2026 – 31.03.2026 (по дате решения)»
  count: number;
  from: string;       // текущий грейд — заполняет руководитель
  to: string;         // целевой грейд
  about: string;      // описание сотрудника от руководителя
}

export const reportPrompt = () => PROMPT;

/** Колонка Google-таблицы, куда вставляется обоснование. */
export const PROMO_COLUMN = 'Письменное обоснование пересмотра';

/**
 * Обоснование повышения для ячейки Google-таблицы: краткая сводка обычным текстом, без списка задач и оформления.
 * Грейды и описание сотрудника — от руководителя, факты — из задач.
 */
export function promoPrompt(p: PromoInfo): string {
  const to = p.to.trim(), from = p.from.trim();
  const target = to ? `на грейд ${to}` : 'на следующий грейд';
  const level = to ? `грейду ${to}` : 'следующему грейду';
  const lines = [
    `Подготовь текст для ячейки Google-таблицы в колонке «${PROMO_COLUMN}» — обоснование повышения сотрудника ${p.name}${from ? ` с грейда ${from}` : ''} ${target}.`,
    `Исходные данные — задачи, в которых участвовал сотрудник${p.period ? ` за период ${p.period}` : ''}: всего ${p.count}.`,
    'Роль в задаче: «исполнитель» — вёл задачу; «был исполнителем» — сделал свою часть и передал дальше (например, в тестирование).',
  ];
  if (p.about.trim()) lines.push('', 'Описание сотрудника от руководителя:', p.about.trim());
  lines.push(
    '',
    'Требования к тексту:',
    '- Краткая сводка: 4–7 предложений, один-два абзаца, примерно до 1000 знаков.',
    `- Без списка задач, их ключей и названий, без разбора отдельных задач. Можно назвать общее количество задач (${p.count}) и основные направления работы в общих словах.`,
    '- Содержание: какую пользу сотрудник принёс команде и продукту в целом; что он умеет — ключевые компетенции, подтверждённые работой;',
    `  почему он соответствует ${level} и почему его стоит повысить.`,
    '- Учитывай описание руководителя и сверяй его с задачами; не выдумывай того, чего нет в данных.',
    '- Обычный текст без Markdown: без заголовков, списков, выделения и эмодзи — его вставят в ячейку таблицы как есть.',
    '- Деловой тон, по-русски, о сотруднике в третьем лице.',
    '- Ответь только самим текстом обоснования, без вступления и пояснений.',
  );
  return lines.join('\n');
}
