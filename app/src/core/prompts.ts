/** Убрать строки с пустыми подстановками описания и грейдов — чтобы не было «Заметки руководителя: ». */
function dropEmpty(template: string, p: PromoInfo): string {
  const empty = (['описание', 'грейд', 'целевой грейд'] as const).filter((k) => !promptVars(p)[k]);
  if (!empty.length) return template;
  return template.split('\n').filter((l) => !empty.some((k) => new RegExp(`\\{\\s*${k}\\s*\\}`, 'i').test(l))).join('\n');
}

/** Подстановки в своём промпте: «{сотрудник}» → «Иван Петров (i.petrov)». */
export const PROMPT_VARS = ['сотрудник', 'период', 'задач', 'грейд', 'целевой грейд', 'описание'] as const;

export function promptVars(p: PromoInfo): Record<(typeof PROMPT_VARS)[number], string> {
  return {
    'сотрудник': p.name, 'период': p.period || 'весь период', 'задач': String(p.count),
    'грейд': p.from.trim(), 'целевой грейд': p.to.trim(), 'описание': p.about.trim(),
  };
}

/** Подставить значения в свой промпт; неизвестные «{…}» остаются как есть. */
export function fillPrompt(template: string, p: PromoInfo): string {
  const vars = promptVars(p) as Record<string, string>;
  return template.replace(/\{([^{}]+)\}/g, (m, name: string) => {
    const k = name.trim().toLowerCase();
    return k in vars ? vars[k] : m;
  });
}

/** Стандартный промпт цели как шаблон — его показываем в редакторе, чтобы было от чего отталкиваться. */
export function defaultTemplate(goal: Goal): string {
  if (goal === 'report') return reportPrompt();
  if (goal !== 'promo') return TEMPLATES[goal];
  const ph = (k: string) => `{${k}}`;
  return promoPrompt({ name: ph('сотрудник'), period: ph('период'), count: ph('задач') as unknown as number, from: ph('грейд'), to: ph('целевой грейд'), about: ph('описание') });
}

/** Текст запроса для цели: свой промпт (если закреплён) или стандартный. */
export function goalPrompt(goal: AiGoal, custom: Partial<Record<Goal, string>>, p: PromoInfo): string {
  if (goal === 'none') return '';
  const tpl = custom[goal]?.trim();
  if (tpl) return fillPrompt(tpl, p);
  if (goal === 'report') return reportPrompt();
  if (goal === 'promo') return promoPrompt(p);
  return fillPrompt(dropEmpty(TEMPLATES[goal], p), p);
}
